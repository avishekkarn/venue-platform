/**
 * Pure domain calculator: QR & Session Lifecycle & Conversion (Views 16 & 17 / Views 6 & 17).
 *
 * Headers View 16:
 * # Sessions Generated is filtered by session createdAt within range.
 * Token ID,Place Type,Place Label,Status,Issued,Revoked,Revoked By,Revocation Reason,Sessions Generated
 *
 * Headers View 17:
 * # Conversion = sessions with >= 1 order / total sessions. Zero-session tokens hidden by default.
 * Token,Place Type,Place Label,Sessions,Orders,Conversion %,Revenue Per Session
 *
 * Governed by D-4.1, D-12.8, BUILD.md §7.1.
 */

import { type Result, ok, fail, DomainErrorCode } from "@/domain/shared/result";
import { parseDecimal, roundToTwoDecimals } from "@/domain/shared/money";
import { type QrLifecycleRow, type ConversionRow } from "./types";

export interface QrTokenReportInput {
  readonly tokenId: string;
  readonly token: string;
  readonly placeType: string;
  readonly placeLabel: string;
  readonly status: "ACTIVE" | "REVOKED";
  readonly issuedAt: Date | string;
  readonly revokedAt?: Date | string | null;
  readonly revokedByStaffName?: string | null;
  readonly revocationReason?: string | null;
  readonly sessions: readonly {
    readonly id: string;
    readonly createdAt: Date | string;
    readonly ordersCount: number;
    readonly revenue: string;
  }[];
}

export function generateQrLifecycle(
  tokens: readonly QrTokenReportInput[],
  range?: { dateFrom?: string; dateTo?: string }
): Result<QrLifecycleRow[]> {
  if (!Array.isArray(tokens)) {
    return fail(DomainErrorCode.VALIDATION_FAILED, "Tokens must be an array");
  }

  const fromTs = range?.dateFrom ? new Date(range.dateFrom).getTime() : 0;
  const toTs = range?.dateTo ? new Date(range.dateTo + "T23:59:59.999Z").getTime() : Infinity;

  const rows: QrLifecycleRow[] = tokens.map((t) => {
    const issuedDate = t.issuedAt instanceof Date ? t.issuedAt : new Date(t.issuedAt);
    const revokedDate = t.revokedAt ? (t.revokedAt instanceof Date ? t.revokedAt : new Date(t.revokedAt)) : null;

    // Filter sessions generated by createdAt within range
    const filteredSessions = (t.sessions ?? []).filter((s: { readonly createdAt: Date | string }) => {
      const sDate = s.createdAt instanceof Date ? s.createdAt : new Date(s.createdAt);
      const sTs = sDate.getTime();
      return !isNaN(sTs) && sTs >= fromTs && sTs <= toTs;
    });

    return {
      tokenId: t.tokenId,
      placeType: t.placeType,
      placeLabel: t.placeLabel,
      status: t.status,
      issued: !isNaN(issuedDate.getTime()) ? issuedDate.toISOString().slice(0, 10) : "—",
      revoked: revokedDate && !isNaN(revokedDate.getTime()) ? revokedDate.toISOString().slice(0, 10) : "—",
      revokedBy: t.revokedByStaffName || "—",
      revocationReason: t.revocationReason || "—",
      sessionsGenerated: filteredSessions.length,
    };
  });

  rows.sort((a, b) => a.placeType.localeCompare(b.placeType) || a.placeLabel.localeCompare(b.placeLabel));

  return ok(rows);
}

export function generateConversion(
  tokens: readonly QrTokenReportInput[]
): Result<ConversionRow[]> {
  if (!Array.isArray(tokens)) {
    return fail(DomainErrorCode.VALIDATION_FAILED, "Tokens must be an array");
  }

  const rows: ConversionRow[] = tokens.map((t) => {
    const sessionsCount = t.sessions?.length || 0;
    let ordersCount = 0;
    let revenueSum = 0;
    let sessionsWithOrders = 0;

    for (const s of t.sessions ?? []) {
      ordersCount += s.ordersCount;
      if (s.ordersCount > 0) sessionsWithOrders += 1;

      const revRes = parseDecimal(s.revenue);
      if (revRes.ok) revenueSum += revRes.value;
    }

    const convNum =
      sessionsCount > 0 ? (sessionsWithOrders / sessionsCount) * 100 : 0;
    const conversionPct = convNum.toFixed(1) + "%";

    const revPerSessionNum =
      sessionsCount > 0 ? revenueSum / sessionsCount : 0;
    const revenuePerSession = roundToTwoDecimals(revPerSessionNum);

    return {
      token: t.token,
      placeType: t.placeType,
      placeLabel: t.placeLabel,
      sessions: sessionsCount,
      orders: ordersCount,
      conversionPct,
      revenuePerSession,
    };
  });

  rows.sort((a, b) => b.orders - a.orders || a.placeLabel.localeCompare(b.placeLabel));

  return ok(rows);
}

export { generateConversion as generateConversionReport };

